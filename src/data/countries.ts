/**
 * Options for `SearchSelect`. Built once at module load — the shape is
 * structurally the component's `SearchSelectOption`, kept import-free so the
 * dataset stays independent of the UI layer.
 */
export const COUNTRY_OPTIONS = COUNTRIES.map((c) => ({
  value: c.name,
  label: c.name,
  keywords: c.alias === undefined ? c.code : `${c.code} ${c.alias}`,
}));

/** Accent- and case-insensitive key so "Turkiye" matches "Türkiye". */
const key = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();

const BY_NAME = new Map(COUNTRIES.map((c) => [key(c.name), c]));

/** The submit-time guard: anything not in the dataset is not a country. */
export function isValidCountryName(name: string): boolean {
  return BY_NAME.has(key(name));
}
